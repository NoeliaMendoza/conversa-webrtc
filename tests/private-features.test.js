const { test } = require('node:test');
const assert = require('node:assert/strict');
const { spawn } = require('node:child_process');
const { once } = require('node:events');
const { io } = require('socket.io-client');

test('privados: autoría, respuestas, reacción única, acuses e aislamiento de terceros', { timeout: 20000 }, async t => {
  const server = spawn(process.execPath, ['server/server.js'], { env: { ...process.env, PORT: '3134', SESSION_SECRET: 'private-features-test' }, stdio: ['ignore', 'pipe', 'pipe'] });
  const clients = [];
  t.after(() => { clients.forEach(socket => socket.disconnect()); server.kill(); });
  await once(server.stdout, 'data');
  const request = (socket, event, payload) => socket.timeout(3000).emitWithAck(event, payload);
  async function client(name) {
    const socket = io('http://localhost:3134', { transports: ['websocket'], autoConnect: false, reconnection: false });
    clients.push(socket); const connected = once(socket, 'connect'); socket.connect(); await connected;
    const response = await request(socket, 'user:join', { name }); socket.user = response.user;
    return socket;
  }
  const a = await client('Noelia'), b = await client('Andrea'), c = await client('Mateo');
  const leaks = [];
  c.on('private:typing:start', message => leaks.push(message));
  c.on('private:typing:stop', message => leaks.push(message));
  const typing = once(b, 'private:typing:start');
  a.emit('private:typing:start', { recipientId: b.user.id, name: 'Falso' });
  assert.deepEqual((await typing)[0], { id: a.user.id, name: 'Noelia' });
  const typingStopped = once(b, 'private:typing:stop');
  a.emit('private:typing:stop');
  assert.equal((await typingStopped)[0].id, a.user.id);
  for (const event of ['private:message', 'private:edit', 'private:delete', 'private:reaction', 'private:received', 'private:read']) c.on(event, message => leaks.push({ event, message }));
  const incoming = once(b, 'private:message');
  await request(a, 'private:message', { recipientId: b.user.id, content: 'Original' });
  const [message] = await incoming;
  assert.equal(message.readAt, undefined);
  assert.equal((await request(a, 'private:read', { id: message.id })).ok, false);
  assert.equal((await request(c, 'private:received', { id: message.id })).ok, false);
  const delivered = once(a, 'private:received');
  await request(b, 'private:received', { id: message.id });
  const [delivery] = await delivered;
  assert.ok(delivery.deliveredAt); assert.equal(delivery.readAt, undefined);
  const read = once(a, 'private:read');
  await request(b, 'private:read', { id: message.id });
  assert.ok((await read)[0].readAt);
  assert.equal((await request(b, 'private:edit', { id: message.id, content: 'Ajeno' })).ok, false);
  assert.equal((await request(c, 'private:edit', { id: message.id, content: 'Intruso' })).ok, false);
  assert.equal((await request(a, 'private:edit', { id: message.id, content: ' ' })).ok, false);
  const edited = once(b, 'private:edit');
  await request(a, 'private:edit', { id: message.id, content: 'Corregido' });
  assert.equal((await edited)[0].content, 'Corregido');
  const responseEvent = once(a, 'private:message');
  await request(b, 'private:message', { recipientId: a.user.id, content: 'Respuesta', replyTo: message.id });
  assert.deepEqual((await responseEvent)[0].reply, { id: message.id, author: 'Noelia', content: 'Corregido' });
  assert.equal((await request(a, 'private:message', { recipientId: c.user.id, content: 'Filtrar', replyTo: message.id })).ok, false);
  assert.equal((await request(c, 'private:reaction', { id: message.id, emoji: '👍' })).ok, false);
  assert.equal((await request(b, 'private:reaction', { id: message.id, emoji: 'invalido' })).ok, false);
  const firstReaction = once(a, 'private:reaction');
  await request(b, 'private:reaction', { id: message.id, emoji: '👍' });
  assert.deepEqual((await firstReaction)[0].reactions, { '👍': [b.user.id] });
  const reaction = once(a, 'private:reaction');
  await request(b, 'private:reaction', { id: message.id, emoji: '❤️' });
  assert.deepEqual((await reaction)[0].reactions, { '❤️': [b.user.id] });
  assert.equal((await request(b, 'private:delete', { id: message.id })).ok, false);
  const deleted = once(b, 'private:delete');
  await request(a, 'private:delete', { id: message.id });
  const [removed] = await deleted;
  assert.equal(removed.content, ''); assert.ok(removed.deletedAt); assert.deepEqual(removed.reactions, {});
  assert.equal((await request(a, 'private:edit', { id: message.id, content: 'Restaurar' })).ok, false);
  assert.equal((await request(b, 'private:reaction', { id: message.id, emoji: '👍' })).ok, false);
  assert.equal((await request(b, 'private:message', { recipientId: a.user.id, content: 'Otra respuesta', replyTo: message.id })).ok, false);
  await request(c, 'private:read', { id: 'barrera' });
  assert.deepEqual(leaks, []);
});
