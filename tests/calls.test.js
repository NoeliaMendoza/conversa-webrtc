const { test } = require('node:test');
const assert = require('node:assert/strict');
const { spawn } = require('node:child_process');
const { once } = require('node:events');
const { io } = require('socket.io-client');

test('solicitudes de llamada: destino, permisos, ocupado, aceptar, rechazar y desconexión', { timeout: 15000 }, async t => {
  const server = spawn(process.execPath, ['server/server.js'], { env: { ...process.env, CALL_STATE_FILE: ':memory:', PORT: '3138', SESSION_SECRET: 'call-signaling-test' }, stdio: ['ignore', 'pipe', 'pipe'] });
  const clients = [];
  t.after(() => { clients.forEach(socket => socket.disconnect()); server.kill(); });
  await once(server.stdout, 'data');
  const request = (socket, event, payload) => socket.timeout(3000).emitWithAck(event, payload);
  async function client(name) {
    const socket = io('http://localhost:3138', { transports: ['websocket'], autoConnect: false, reconnection: false });
    clients.push(socket); const connected = once(socket, 'connect'); socket.connect(); await connected;
    if (name) socket.user = (await request(socket, 'user:join', { name })).user;
    return socket;
  }
  const a = await client('Noelia'), b = await client('Andrea'), c = await client('Mateo'), visitor = await client();
  const leaks = [];
  ['call:incoming', 'call:accepted', 'call:rejected', 'call:ended', 'webrtc:offer', 'webrtc:answer', 'webrtc:ice-candidate'].forEach(event => c.on(event, value => leaks.push(value)));
  assert.equal((await request(visitor, 'call:start', { recipientId: a.user.id })).ok, false);
  assert.equal((await request(a, 'call:start', { recipientId: a.user.id })).ok, false);
  assert.equal((await request(a, 'call:start', { recipientId: 'desconocido' })).ok, false);
  assert.equal((await request(a, 'call:start', { recipientId: b.user.id, mode: 'invalid' })).ok, false);
  const incoming = once(b, 'call:incoming');
  const started = await request(a, 'call:start', { recipientId: b.user.id, callerId: c.user.id });
  assert.equal(started.ok, true);
  const [call] = await incoming;
  assert.equal(call.mode, 'video');
  assert.equal(call.caller.id, a.user.id);
  assert.equal(call.recipient.id, b.user.id);
  assert.equal((await request(c, 'call:start', { recipientId: b.user.id })).ok, false);
  assert.equal((await request(a, 'call:accept', { callId: call.id })).ok, false);
  assert.equal((await request(c, 'call:accept', { callId: call.id })).ok, false);
  assert.equal((await request(a, 'webrtc:offer', { callId: call.id, description: { type: 'offer', sdp: 'v=0\r\n' } })).ok, false);
  const acceptedA = once(a, 'call:accepted'), acceptedB = once(b, 'call:accepted');
  assert.equal((await request(b, 'call:accept', { callId: call.id })).ok, true);
  assert.deepEqual((await acceptedA)[0], (await acceptedB)[0]);
  const description = { type: 'offer', sdp: 'v=0\r\n' };
  assert.equal((await request(c, 'webrtc:offer', { callId: call.id, description })).ok, false);
  assert.equal((await request(b, 'webrtc:offer', { callId: call.id, description })).ok, false);
  assert.equal((await request(a, 'webrtc:offer', { callId: call.id, description: { type: 'offer', sdp: 3 } })).ok, false);
  const offer = once(b, 'webrtc:offer');
  assert.equal((await request(a, 'webrtc:offer', { callId: call.id, description, recipientId: c.user.id })).ok, true);
  assert.deepEqual((await offer)[0], { callId: call.id, revision: 0, description });
  const answer = once(a, 'webrtc:answer');
  assert.equal((await request(b, 'webrtc:answer', { callId: call.id, description: { type: 'answer', sdp: 'v=0\r\n' } })).ok, true);
  assert.equal((await answer)[0].description.type, 'answer');
  const ice = once(b, 'webrtc:ice-candidate');
  assert.equal((await request(a, 'webrtc:ice-candidate', { callId: call.id, candidate: { candidate: 'candidate:test', sdpMid: '0', sdpMLineIndex: 0 } })).ok, true);
  assert.equal((await ice)[0].candidate.sdpMid, '0');
  assert.equal((await request(a, 'webrtc:ice-candidate', { callId: call.id, candidate: {} })).ok, false);
  assert.equal((await request(c, 'call:end', { callId: call.id })).ok, false);
  const ended = once(a, 'call:ended');
  await request(b, 'call:end', { callId: call.id });
  assert.equal((await ended)[0].status, 'ended');
  const nextIncoming = once(b, 'call:incoming');
  await request(a, 'call:start', { recipientId: b.user.id, mode: 'audio' });
  const second = (await nextIncoming)[0];
  assert.equal(second.mode, 'audio');
  const rejected = once(a, 'call:rejected');
  await request(b, 'call:reject', { callId: second.id });
  assert.equal((await rejected)[0].reason, 'rejected');
  const lastIncoming = once(b, 'call:incoming');
  await request(a, 'call:start', { recipientId: b.user.id });
  await lastIncoming;
  const disconnected = once(a, 'call:ended');
  b.disconnect();
  assert.equal((await disconnected)[0].reason, 'disconnected');
  const chat = once(c, 'message:new');
  await request(a, 'message:new', { content: 'El chat sigue funcionando después de la solicitud.' });
  assert.equal((await chat)[0].authorId, a.user.id);
  await request(c, 'call:end', { callId: 'barrera' });
  assert.deepEqual(leaks, []);
});
