const { test } = require('node:test');
const assert = require('node:assert/strict');
const { spawn } = require('node:child_process');
const { once } = require('node:events');
const { io } = require('socket.io-client');

function next(socket, event, matches = () => true) {
  return new Promise((resolve, reject) => {
    const timeout = setTimeout(() => { socket.off(event, handler); reject(new Error(`Tiempo agotado: ${event}`)); }, 4000);
    function handler(data) {
      if (!matches(data)) return;
      clearTimeout(timeout);
      socket.off(event, handler);
      resolve(data);
    }
    socket.on(event, handler);
  });
}

test('chat grupal: validación, difusión, historial, presencia y caída del servidor', { timeout: 20000 }, async t => {
  const server = spawn(process.execPath, ['server/server.js'], { env: { ...process.env, PORT: '3127' }, stdio: ['ignore', 'pipe', 'pipe'] });
  const clients = [];
  t.after(() => { clients.forEach(client => client.disconnect()); server.kill(); });
  await once(server.stdout, 'data');
  async function client() {
    const socket = io('http://localhost:3127', { transports: ['websocket'], autoConnect: false, reconnection: false });
    clients.push(socket);
    const connected = next(socket, 'connect');
    socket.connect();
    await connected;
    return socket;
  }
  function request(socket, event, payload) {
    return socket.timeout(4000).emitWithAck(event, payload);
  }
  const a = await client();
  const b = await client();
  const visitor = await client();
  assert.equal((await request(visitor, 'message:new', { content: 'Sin ingresar' })).ok, false);
  assert.equal((await request(visitor, 'presence:set', { status: 'away' })).ok, false);
  assert.equal((await request(visitor, 'message:search', { query: 'hola' })).ok, false);
  assert.equal((await request(a, 'user:join', { name: '  ' })).ok, false);
  const joinedA = await request(a, 'user:join', { name: 'Noelia' });
  assert.equal(joinedA.ok, true);
  a.userId = joinedA.user.id;
  assert.equal((await request(b, 'user:join', { name: 'noelia' })).ok, false);
  const presence = next(a, 'users:update');
  const joinedB = await request(b, 'user:join', { name: 'Andrea' });
  assert.equal(joinedB.ok, true);
  b.userId = joinedB.user.id;
  assert.equal((await presence).length, 2);
  // Reto 1: el servidor identifica al autor y detiene el aviso explícitamente.
  const writing = next(b, 'typing:start');
  a.emit('typing:start', { name: 'Identidad falsa' });
  assert.deepEqual(await writing, { id: a.userId, name: 'Noelia' });
  const stopped = next(b, 'typing:stop');
  a.emit('typing:stop');
  assert.equal((await stopped).id, a.userId);
  // El indicador caduca aunque falte el evento de parada del cliente.
  const writingAgain = next(b, 'typing:start');
  const expired = next(b, 'typing:stop');
  a.emit('typing:start');
  await writingAgain;
  assert.equal((await expired).id, a.userId);
  assert.equal((await request(a, 'message:new', { content: ' ' })).ok, false);
  let leaked = false;
  visitor.on('message:new', () => { leaked = true; });
  const receivedA = next(a, 'message:new');
  const receivedB = next(b, 'message:new');
  assert.equal((await request(a, 'message:new', { content: 'Hola grupo' })).ok, true);
  const [messageA, messageB] = await Promise.all([receivedA, receivedB]);
  assert.deepEqual(messageA, messageB);
  assert.equal(messageA.author, 'Noelia');
  assert.equal(messageA.content, 'Hola grupo');
  assert.ok(messageA.id);
  assert.ok(!Number.isNaN(Date.parse(messageA.createdAt)));
  // Reto 3: control de acceso, conteo compartido y eliminación de la reacción propia.
  assert.equal((await request(visitor, 'reaction:toggle', { id: messageA.id, emoji: '👍' })).ok, false);
  assert.equal((await request(a, 'reaction:toggle', { id: messageA.id, emoji: 'X' })).ok, false);
  assert.equal((await request(a, 'reaction:toggle', { id: 'inexistente', emoji: '👍' })).ok, false);
  const reactionA = next(a, 'reaction:update');
  const reactionB = next(b, 'reaction:update');
  assert.equal((await request(a, 'reaction:toggle', { id: messageA.id, emoji: '👍', userId: b.userId })).ok, true);
  const [firstA, firstB] = await Promise.all([reactionA, reactionB]);
  assert.deepEqual(firstA, firstB);
  assert.deepEqual(firstA.reactions['👍'], [a.userId]);
  const twoReactions = next(a, 'reaction:update');
  await request(b, 'reaction:toggle', { id: messageA.id, emoji: '👍' });
  assert.deepEqual((await twoReactions).reactions['👍'], [a.userId, b.userId]);
  const removedReaction = next(a, 'reaction:update');
  await request(a, 'reaction:toggle', { id: messageA.id, emoji: '👍' });
  assert.deepEqual((await removedReaction).reactions['👍'], [b.userId]);
  const heart = next(a, 'reaction:update');
  await request(a, 'reaction:toggle', { id: messageA.id, emoji: '❤️' });
  assert.deepEqual((await heart).reactions['❤️'], [a.userId]);
  const replaced = next(a, 'reaction:update');
  await request(a, 'reaction:toggle', { id: messageA.id, emoji: '😂' });
  const replacement = await replaced;
  assert.equal(replacement.reactions['❤️'], undefined);
  assert.deepEqual(replacement.reactions['😂'], [a.userId]);
  assert.deepEqual(replacement.reactions['👍'], [b.userId]);
  const restored = next(a, 'reaction:update');
  await request(a, 'reaction:toggle', { id: messageA.id, emoji: '❤️' });
  assert.equal((await restored).reactions['😂'], undefined);
  assert.equal((await request(visitor, 'message:edit', { id: messageA.id, content: 'Intruso' })).ok, false);
  assert.equal((await request(b, 'message:edit', { id: messageA.id, content: 'Otro autor' })).ok, false);
  assert.equal((await request(a, 'message:edit', { id: 'inexistente', content: 'Hola' })).ok, false);
  assert.equal((await request(a, 'message:edit', { id: messageA.id, content: ' ' })).ok, false);
  assert.equal((await request(a, 'message:edit', { id: messageA.id, content: 'x'.repeat(2001) })).ok, false);
  const editedA = next(a, 'message:edit');
  const editedB = next(b, 'message:edit');
  assert.equal((await request(a, 'message:edit', { id: messageA.id, content: 'Hola grupo, corregido' })).ok, true);
  const [changeA, changeB] = await Promise.all([editedA, editedB]);
  assert.deepEqual(changeA, changeB);
  assert.equal(changeA.id, messageA.id);
  assert.equal(changeA.createdAt, messageA.createdAt);
  assert.equal(changeA.content, 'Hola grupo, corregido');
  assert.ok(!Number.isNaN(Date.parse(changeA.editedAt)));
  // Reto 12: búsqueda del contenido actualizado, con validación y sin distinguir mayúsculas.
  assert.equal((await request(a, 'message:search', { query: 'a' })).ok, false);
  assert.equal((await request(a, 'message:search', { query: 'x'.repeat(101) })).ok, false);
  const found = await request(a, 'message:search', { query: 'HOLA GRUPO' });
  assert.equal(found.ok, true);
  assert.equal(found.total, 1);
  assert.equal(found.messages[0].id, messageA.id);
  assert.equal(found.messages[0].content, 'Hola grupo, corregido');
  assert.equal((await request(a, 'message:search', { query: 'sin-coincidencias' })).total, 0);
  // Reto 11: el servidor resuelve la cita y la difunde, sin aceptar texto falsificado.
  assert.equal((await request(b, 'message:new', { content: 'Respuesta', replyTo: 'inexistente' })).ok, false);
  const replyA = next(a, 'message:new');
  const replyB = next(b, 'message:new');
  await request(b, 'message:new', { content: 'De acuerdo', replyTo: messageA.id, reply: { author: 'Falso', content: 'Falso' } });
  const [quotedA, quotedB] = await Promise.all([replyA, replyB]);
  assert.deepEqual(quotedA, quotedB);
  assert.deepEqual(quotedA.reply, { id: messageA.id, author: 'Noelia', content: 'Hola grupo, corregido' });
  // Reto 13: acceso, difusión, reemplazo y actualización de un destacado.
  assert.equal((await request(visitor, 'message:pin', { id: messageA.id })).ok, false);
  assert.equal((await request(b, 'message:pin', { id: 'inexistente' })).ok, false);
  const pinA = next(a, 'pin:update');
  const pinB = next(b, 'pin:update');
  assert.equal((await request(b, 'message:pin', { id: messageA.id })).ok, true);
  const [pinnedA, pinnedB] = await Promise.all([pinA, pinB]);
  assert.deepEqual(pinnedA, pinnedB);
  assert.equal(pinnedA.message.id, messageA.id);
  assert.equal(pinnedA.pinnedBy, 'Andrea');
  const replacedPin = next(a, 'pin:update');
  await request(b, 'message:pin', { id: quotedA.id });
  assert.equal((await replacedPin).message.id, quotedA.id);
  const editedPin = next(a, 'pin:update');
  await request(b, 'message:edit', { id: quotedA.id, content: 'Respuesta destacada actualizada' });
  assert.equal((await editedPin).message.content, 'Respuesta destacada actualizada');
  const thirdJoined = next(a, 'users:update');
  const history = await request(visitor, 'user:join', { name: 'Mateo' });
  visitor.userId = history.user.id;
  assert.equal(history.pinned.message.id, quotedA.id);
  assert.equal(history.pinned.message.content, 'Respuesta destacada actualizada');
  assert.equal((await thirdJoined).length, 3);
  assert.equal(history.messages[0].id, messageA.id);
  assert.equal(history.messages[0].content, 'Hola grupo, corregido');
  assert.equal(history.messages[0].editedAt, changeA.editedAt);
  assert.deepEqual(history.messages.find(message => message.id === quotedA.id).reply, quotedA.reply);
  assert.deepEqual(history.messages[0].reactions['👍'], [b.userId]);
  assert.deepEqual(history.messages[0].reactions['❤️'], [a.userId]);
  assert.equal(leaked, false);
  // Reto 14: estados compartidos y cambio limitado a la identidad de la conexión.
  assert.equal((await request(b, 'presence:set', { status: 'offline' })).ok, false);
  assert.equal((await request(b, 'presence:set', { status: 'inventado' })).ok, false);
  const awayA = next(a, 'presence:update', roster => roster.some(user => user.id === b.userId && user.status === 'away'));
  const awayC = next(visitor, 'presence:update', roster => roster.some(user => user.id === b.userId && user.status === 'away'));
  assert.equal((await request(b, 'presence:set', { status: 'away', userId: a.userId })).ok, true);
  const [rosterA, rosterC] = await Promise.all([awayA, awayC]);
  assert.deepEqual(rosterA, rosterC);
  assert.equal(rosterA.find(user => user.id === a.userId).status, 'online');
  const backOnline = next(a, 'presence:update', roster => roster.some(user => user.id === b.userId && user.status === 'online'));
  await request(b, 'presence:set', { status: 'online' });
  await backOnline;
  assert.equal((await request(a, 'message:unpin', { id: messageA.id })).ok, false);
  const unpinned = next(b, 'pin:update');
  assert.equal((await request(a, 'message:unpin', { id: quotedA.id })).ok, true);
  assert.equal(await unpinned, null);
  // Reto 6: entrega privada en ambos sentidos, sin filtración al tercer cliente.
  const privateLeaks = [];
  visitor.on('private:message', message => privateLeaks.push(message));
  assert.equal((await request(a, 'private:message', { recipientId: b.userId, content: ' ' })).ok, false);
  assert.equal((await request(a, 'private:message', { recipientId: b.userId, content: 'x'.repeat(2001) })).ok, false);
  assert.equal((await request(a, 'private:message', { recipientId: a.userId, content: 'Para mí' })).ok, false);
  assert.equal((await request(a, 'private:message', { recipientId: 'desconocido', content: 'Hola' })).ok, false);
  const privateA = next(a, 'private:message');
  const privateB = next(b, 'private:message');
  assert.equal((await request(a, 'private:message', { recipientId: b.userId, content: 'Solo para Andrea', authorId: visitor.userId })).ok, true);
  const [secretA, secretB] = await Promise.all([privateA, privateB]);
  assert.deepEqual(secretA, secretB);
  assert.equal(secretA.authorId, a.userId);
  assert.equal(secretA.author, 'Noelia');
  assert.equal(secretA.recipientId, b.userId);
  assert.equal(secretA.recipient, 'Andrea');
  assert.equal(secretA.content, 'Solo para Andrea');
  assert.equal((await request(visitor, 'message:search', { query: 'Solo para Andrea' })).total, 0);
  assert.ok(secretA.id);
  assert.ok(!Number.isNaN(Date.parse(secretA.createdAt)));
  const privateReplyA = next(a, 'private:message');
  const privateReplyB = next(b, 'private:message');
  await request(b, 'private:message', { recipientId: a.userId, content: 'Respuesta privada' });
  assert.deepEqual(await privateReplyA, await privateReplyB);
  assert.equal((await request(a, 'message:new', { content: 'Intento citar privado', replyTo: secretA.id })).ok, false);
  // La respuesta del tercer socket actúa como barrera para comprobar lo recibido.
  await request(visitor, 'private:message', { recipientId: 'desconocido', content: 'Barrera' });
  assert.deepEqual(privateLeaks, []);
  // Reto 4: solo el autor elimina; la marca se sincroniza y llega al historial.
  const disposable = next(a, 'message:new');
  await request(a, 'message:new', { content: 'Mensaje a eliminar' });
  const target = await disposable;
  const replyToDeleted = next(a, 'message:new');
  await request(b, 'message:new', { content: 'Respondo al que se eliminará', replyTo: target.id });
  const dependent = await replyToDeleted;
  await request(a, 'message:edit', { id: target.id, content: 'Texto actualizado de la cita' });
  const pinnedForDeletion = next(a, 'pin:update');
  await request(b, 'message:pin', { id: target.id });
  await pinnedForDeletion;
  const outsider = await client();
  assert.equal((await request(outsider, 'private:message', { recipientId: a.userId, content: 'Sin sesión' })).ok, false);
  assert.equal((await request(outsider, 'message:delete', { id: target.id })).ok, false);
  assert.equal((await request(b, 'message:delete', { id: target.id, authorId: a.userId })).ok, false);
  assert.equal((await request(a, 'message:delete', { id: 'inexistente' })).ok, false);
  const deletedA = next(a, 'message:delete');
  const deletedB = next(b, 'message:delete');
  const deletedC = next(visitor, 'message:delete');
  const pinDeleted = next(a, 'pin:update');
  assert.equal((await request(a, 'message:delete', { id: target.id })).ok, true);
  assert.equal(await pinDeleted, null);
  const removed = await Promise.all([deletedA, deletedB, deletedC]);
  assert.deepEqual(removed[0], removed[1]);
  assert.deepEqual(removed[1], removed[2]);
  assert.equal(removed[0].content, '');
  assert.deepEqual(removed[0].reactions, {});
  assert.ok(removed[0].deletedAt);
  assert.equal((await request(a, 'message:delete', { id: target.id })).ok, false);
  assert.equal((await request(a, 'message:edit', { id: target.id, content: 'Restaurar' })).ok, false);
  assert.equal((await request(b, 'message:new', { content: 'Cita inválida', replyTo: target.id })).ok, false);
  assert.equal((await request(b, 'message:pin', { id: target.id })).ok, false);
  assert.equal((await request(b, 'reaction:toggle', { id: target.id, emoji: '👍' })).ok, false);
  const joinedFourth = next(a, 'users:update');
  const deletionHistory = await request(outsider, 'user:join', { name: 'Lucía' });
  await joinedFourth;
  assert.equal(deletionHistory.pinned, null);
  assert.equal(deletionHistory.messages.some(message => message.id === secretA.id || message.content === 'Respuesta privada'), false);
  assert.equal(deletionHistory.messages.find(message => message.id === target.id).content, '');
  assert.ok(deletionHistory.messages.find(message => message.id === target.id).deletedAt);
  assert.equal((await request(a, 'message:search', { query: 'Texto actualizado de la cita' })).total, 0);
  const deletedQuote = deletionHistory.messages.find(message => message.id === dependent.id).reply;
  assert.equal(deletedQuote.content, 'Mensaje eliminado');
  assert.equal(deletedQuote.deleted, true);
  const fourthLeft = next(a, 'users:update');
  const fourthLeaveNotice = next(a, 'user:leave', user => user.name === 'Lucía');
  outsider.disconnect();
  await Promise.all([fourthLeft, fourthLeaveNotice]);
  const updated = next(a, 'users:update');
  const left = next(a, 'user:leave', user => user.name === 'Andrea');
  const leavingWriter = next(a, 'typing:start');
  b.emit('typing:start');
  await leavingWriter;
  const stoppedOnLeave = next(a, 'typing:stop');
  const leavingId = b.userId;
  const offlinePresence = next(a, 'presence:update', roster => roster.some(user => user.id === leavingId && user.status === 'offline'));
  b.disconnect();
  const offlineRoster = await offlinePresence;
  assert.equal(offlineRoster.find(user => user.id === leavingId).status, 'offline');
  // Reto 8: fecha de desconexión emitida por el servidor y compartida con el grupo.
  const lastSeen = offlineRoster.find(user => user.id === leavingId).disconnectedAt;
  assert.ok(!Number.isNaN(Date.parse(lastSeen)));
  assert.ok(Math.abs(Date.now() - Date.parse(lastSeen)) < 5000);
  assert.equal((await stoppedOnLeave).id, leavingId);
  assert.equal((await updated).length, 2);
  assert.equal((await left).name, 'Andrea');
  assert.equal((await request(a, 'private:message', { recipientId: leavingId, content: '¿Sigues ahí?' })).ok, false);
  const disconnected = next(a, 'disconnect');
  server.kill();
  await disconnected;
  const exit = server.exitCode === null ? once(server, 'exit') : Promise.resolve();
  await exit;
});
